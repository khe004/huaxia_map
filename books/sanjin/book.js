function cnNumY(n) {
  const D = '〇一二三四五六七八九';
  if (n === 1) return '元';
  if (n < 10) return D[n];
  const t = Math.floor(n / 10), o = n % 10;
  return (t === 1 ? '' : D[t]) + '十' + (o ? D[o] : '');
}

