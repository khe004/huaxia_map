const NUM = n => (n === 1 ? '元' : n < 10 ? '〇一二三四五六七八九'[n] : n % 10 ? (n < 20 ? '十' : '〇一二三四五六七八九'[Math.floor(n / 10)] + '十') + '〇一二三四五六七八九'[n % 10] : (n < 20 ? '' : '〇一二三四五六七八九'[n / 10]) + '十');
function H(r, n, m, extra) {
  const y0 = ERA[r] + n - 1;
  let y = y0, mo = !m ? 6 : m + 1;
  if (m === 12) { y = y0 + 1; mo = 1; }
  return { y, mo: Math.min(mo + (extra || 0), 12.9), cal: `${r}${NUM(n)}年${m ? MON[m] : ''}` };
}

