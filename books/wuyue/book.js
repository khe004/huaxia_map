function cnNumY(n) {
  const D = '〇一二三四五六七八九';
  if (n === 1) return '元';
  if (n < 10) return D[n];
  const t = Math.floor(n / 10), o = n % 10;
  return (t === 1 ? '' : D[t]) + '十' + (o ? D[o] : '');
}
function reignOf(L, y) { let r = L[0]; for (const it of L) if (it[0] <= y) r = it; return `${r[1]}${cnNumY(y - r[0] + 1)}年`; }
function chunqiuYear(y) { return [{ d: '鲁', s: reignOf(LU, y) }, { d: '周', s: reignOf(ZHOU, y) }]; }
