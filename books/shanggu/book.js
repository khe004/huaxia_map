function cnNumY(n) {
  const D = '〇一二三四五六七八九';
  if (n === 1) return '元';
  if (n < 10) return D[n];
  const t = Math.floor(n / 10), o = n % 10;
  return (t === 1 ? '' : D[t]) + '十' + (o ? D[o] : '');
}
function shangguYear(y) {
  if (y < -2070) return [{ d: '', s: y < -3000 ? '新石器时代 · 仰韶时代' : '新石器时代 · 龙山时代（五帝传说）' }];
  if (y < -1600) return [{ d: '', s: '夏' }];
  if (y >= -841) {
    if (y < -827) return [{ d: '', s: `周 共和${cnNumY(y + 842)}年` }];
    if (y < -781) return [{ d: '', s: `周宣王${cnNumY(y + 828)}年` }];
    return [{ d: '', s: `周幽王${cnNumY(y + 782)}年` }];
  }
  let r = SG_KINGS[0]; for (const k of SG_KINGS) if (k[0] <= y) r = k;
  return [{ d: '', s: `${r[1]} · ${r[2]}${r[2].endsWith('以后') ? '' : '时期'}` }];
}

